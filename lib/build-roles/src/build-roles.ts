const compareAscii = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);

const listVisibleEntries = (dir: string): string[] => {
  if (!existsSync(dir)) {
    return [];
  }
  return readdirSync(dir)
    .filter((entry) => !entry.startsWith("."))
    .sort(compareAscii);
};

const findMarkdownFiles = (dir: string, minDepth: number, currentDepth = 1): string[] => {
  if (!existsSync(dir)) {
    return [];
  }
  const results: string[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) =>
    compareAscii(a.name, b.name),
  )) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...findMarkdownFiles(fullPath, minDepth, currentDepth + 1));
    } else if (entry.isFile() && currentDepth >= minDepth && entry.name.endsWith(".md")) {
      results.push(fullPath);
    }
  }
  return results.sort(compareAscii);
};

const toPosixRel = (baseDir: string, targetPath: string): string =>
  path.relative(baseDir, targetPath).split(path.sep).join("/");

const writeIfChanged = (filePath: string, content: string, written: string[]): void => {
  if (existsSync(filePath)) {
    const existing = readFileSync(filePath, "utf8");
    if (existing === content) {
      return;
    }
  }
  mkdirSync(path.dirname(filePath), { recursive: true });
  writeFileSync(filePath, content, "utf8");
  written.push(filePath);
};

export const githubHeadingSlugs = (markdown: string): string[] => {
  const counts = new Map<string, number>();
  const slugs: string[] = [];
  const headingPattern = /^ {0,3}#{1,6}\s+(.+?)\s*#*\s*$/gm;
  for (const match of markdown.matchAll(headingPattern)) {
    let heading = match[1] ?? "";
    heading = heading.replace(/!?(?:\[([^\]]*)\])\([^)]*\)/g, "$1");
    heading = heading.replace(/<[^>]+>/g, "");
    heading = heading.replace(/[`*_~]/g, "");
    heading = heading.toLowerCase();
    let base = heading.replace(/[^\p{L}\p{N}\s_-]/gu, "");
    base = base.replace(/^\s+|\s+$/g, "");
    base = base.replace(/\s/g, "-");
    const count = counts.get(base) ?? 0;
    counts.set(base, count + 1);
    slugs.push(count > 0 ? `${base}-${count}` : base);
  }
  return slugs;
};

export const checkRuleFormat = (content: string, fileName: string): string | null => {
  const lines = content.endsWith("\n")
    ? content.slice(0, -1).split("\n")
    : content.length === 0
      ? []
      : content.split("\n");

  const line0 = lines[0];
  if (line0 === undefined || !/^## \S/.test(line0)) {
    return "line 1 is not `## <title>`";
  }
  if (lines.length <= 1 || lines[1] !== "") {
    return "line 2 is not blank";
  }
  const line2 = lines[2];
  if (line2 === undefined || !/^\*\*(?:Law|Default|Preference|Tooling):\*\* \S/.test(line2)) {
    return "line 3 does not start with `**Law:** `, `**Default:** `, `**Preference:** `, or `**Tooling:** ` and then text";
  }
  if (lines.length <= 3 || lines[3] !== "") {
    return "line 4 is not blank";
  }
  const line4 = lines[4];
  if (line4 === undefined || !/^\*\*When:\*\* \S/.test(line4)) {
    return "line 5 does not start with `**When:** ` and then text";
  }
  if (lines.length <= 5 || lines[5] !== "") {
    return "line 6 is not blank";
  }

  let inCode = false;
  let bad = 0;
  let good = 0;
  let first = "";
  let head = 0;
  let links = 0;
  let early = false;
  let url = 0;
  let last = 0;
  let stray = 0;

  for (let i = 6; i < lines.length; i += 1) {
    const line = lines[i] ?? "";
    if (/^ {0,3}```/.test(line)) {
      inCode = !inCode;
      last = i + 1;
      continue;
    }
    if (/\S/.test(line)) {
      last = i + 1;
    }
    if (inCode) {
      continue;
    }
    if (head === 0 && /^ {0,3}#{1,6} /.test(line)) {
      head = i + 1;
    }
    if (line.startsWith("Bad:")) {
      bad += 1;
      if (first === "") {
        first = "Bad";
      }
    }
    if (line.startsWith("Good:")) {
      good += 1;
      if (first === "") {
        first = "Good";
      }
    }
    if (/^Links: \S/.test(line)) {
      links += 1;
      if (good === 0) {
        early = true;
      }
      url = i + 1;
    } else if (/https?:\/\//.test(line)) {
      if (stray === 0) {
        stray = i + 1;
      }
    }
  }

  if (stray === 0 && /https?:\/\//.test(line2)) {
    stray = 3;
  }
  if (stray === 0 && /https?:\/\//.test(line4)) {
    stray = 5;
  }

  if (stray !== 0) {
    return `line ${stray} holds a URL; a URL goes on the \`Links:\` line`;
  }
  if (links > 1) {
    return "has more than one `Links:` line";
  }
  if (early) {
    return "has `Links:` before `Good:`";
  }
  if (links > 0 && url !== last) {
    return "`Links:` is not the last line";
  }
  if (bad !== 1) {
    return `needs exactly one line starting \`Bad:\` outside code blocks, and has ${bad}`;
  }
  if (good !== 1) {
    return `needs exactly one line starting \`Good:\` outside code blocks, and has ${good}`;
  }
  if (first !== "Bad") {
    return "has `Good:` before `Bad:`";
  }
  if (head !== 0) {
    return `line ${head} is a heading; only line 1 is one`;
  }

  const base = path.basename(fileName, ".md");
  if (base.includes("--") || /[^a-z0-9-]/.test(base)) {
    return "the file name must be lowercase letters, digits, and single hyphens";
  }

  const slug = githubHeadingSlugs(line0)[0] ?? "";
  if (slug.includes("--")) {
    return `the title's slug ${slug} has a double hyphen; reword the title`;
  }
  if (base !== slug) {
    return `the file name must be the slug of the title, ${slug}.md`;
  }

  return null;
};

export const checkCitations = (
  content: string,
  reportPath: string,
  rulesDir: string,
  ruleFolders: readonly string[],
  slugCache?: Map<string, Set<string>>,
): string[] => {
  if (ruleFolders.length === 0) {
    return [];
  }
  const errors: string[] = [];
  const folderAlternation = ruleFolders.join("|");
  const pathRegex = new RegExp(`(?:${folderAlternation})/[a-z0-9-]+\\.md`, "g");
  const refRegex = new RegExp(`(?:${folderAlternation})/[a-z0-9-]+\\.md#[^\\]\\s\`),;]+`, "g");

  const citedPaths = [...new Set(content.match(pathRegex) ?? [])].sort(compareAscii);
  for (const citedPath of citedPaths) {
    if (!existsSync(path.join(rulesDir, citedPath))) {
      errors.push(`${reportPath}: cites ${citedPath}, and no rule file has that path`);
    }
  }

  const citedRefs = [
    ...new Set((content.match(refRegex) ?? []).map((ref) => ref.replace(/\.$/, ""))),
  ].sort(compareAscii);
  for (const ref of citedRefs) {
    const hashIdx = ref.indexOf("#");
    const rulePath = ref.slice(0, hashIdx);
    const slug = ref.slice(hashIdx + 1);
    const fullPath = path.join(rulesDir, rulePath);
    if (!existsSync(fullPath)) {
      errors.push(`${reportPath}: cites ${ref}, and ${rulePath} has no heading with that slug`);
      continue;
    }
    let slugs = slugCache?.get(fullPath);
    if (!slugs) {
      slugs = new Set(githubHeadingSlugs(readFileSync(fullPath, "utf8")));
      slugCache?.set(fullPath, slugs);
    }
    if (!slugs.has(slug)) {
      errors.push(`${reportPath}: cites ${ref}, and ${rulePath} has no heading with that slug`);
    }
  }

  return errors;
};

const readList = (listsDir: string, name: string): string[] => {
  const listPath = path.join(listsDir, `rules-${name}.list`);
  if (!existsSync(listPath)) {
    return [];
  }
  return readFileSync(listPath, "utf8")
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line.length > 0 && !line.startsWith("#"));
};

const rulesBlock = (readsCsv: string): string => {
  const reads = readsCsv.split(",").filter((item) => item.length > 0);
  const bullets = reads.map((item) => `- \`rules-${item}.md\``).join("\n");
  return [
    "## Rules",
    "",
    "The house rules are in files in the same folder as this file. Before you start work, read every file in this list, in full. Each ends with a line `<!-- end of … -->`; if your read stopped before that line, read on from where it stopped.",
    "",
    bullets,
    "",
    "A Law outranks a spec, a plan, and a brief. A rule cited by its library path, such as `invariants/never-blindly-retry-a-non-idempotent-operation.md`, sits under its `<!-- rule: <path> -->` line in one of the `rules-*.md` files in that folder.",
    "",
    "",
  ].join("\n");
};

export const buildRoles = (repoDir: string): BuildRolesResult => {
  const errors: string[] = [];
  const warnings: string[] = [];
  const written: string[] = [];
  const expectedGenerated = new Set<string>();
  const slugCache = new Map<string, Set<string>>();

  const fail = (message: string): void => {
    errors.push(message);
  };

  const rulesDir = path.join(repoDir, "skills/meridian/references/rules");
  const listsDir = path.join(repoDir, "skills/meridian/references");

  const listNames = listVisibleEntries(listsDir)
    .map((entry) => /^rules-(.+)\.list$/.exec(entry)?.[1])
    .filter((name): name is string => name !== undefined);

  if (listNames.length === 0) {
    fail("skills/meridian/references: holds no rules-<name>.list");
    return { exitCode: 1, errors, warnings, written };
  }

  const ruleFolders = listVisibleEntries(rulesDir);
  for (const folder of ruleFolders) {
    if (!/^[a-z-]*$/.test(folder)) {
      fail(`${rulesDir}: holds a name outside [a-z-]`);
      return { exitCode: 1, errors, warnings, written };
    }
  }

  // Write the seven index files under rules/core/ from each rule's strength line.
  for (const spec of INDEX_SPECS) {
    const lines: string[] = [
      spec.heading,
      "",
      `${GENERATED_STAMP} from each rule's strength line. Change the rule, then rebuild; do not edit this file. -->`,
      "",
      "Each line is one rule: its title, its one sentence, and the file that holds it.",
      "",
    ];
    let count = 0;
    for (const listName of spec.lists) {
      for (const rule of readList(listsDir, listName)) {
        if (EXEMPT.has(rule)) {
          continue;
        }
        const rulePath = path.join(rulesDir, rule);
        if (!existsSync(rulePath)) {
          continue;
        }
        const ruleLines = readFileSync(rulePath, "utf8").split("\n");
        const first = ruleLines[0] ?? "";
        const third = ruleLines[2] ?? "";
        if (!/^## .+/.test(first)) {
          continue;
        }
        const strengthPrefix = `**${spec.strength}:** `;
        if (!third.startsWith(strengthPrefix) || third.length <= strengthPrefix.length) {
          continue;
        }
        let title = first.slice(3);
        if (!/[.!?:;]$/.test(title)) {
          title = `${title}.`;
        }
        lines.push(`- **${title}** ${third.slice(strengthPrefix.length)} [\`${rule}\`]`);
        count += 1;
      }
    }
    if (count === 0) {
      lines.push("- none");
    }
    if (spec.rulePath === "core/laws.md") {
      lines.push(
        "",
        "A Law beats any spec or plan Decision: when a design and a Law conflict, the design changes, and a Decision that breaks one is a defect, not a choice.",
      );
    }
    writeIfChanged(path.join(rulesDir, spec.rulePath), `${lines.join("\n")}\n`, written);
  }

  // Every rule is in exactly one list (an unlisted index file: in none), and follows the rule format.
  const listCounts = new Map<string, number>();
  for (const name of listNames) {
    for (const rule of readList(listsDir, name)) {
      listCounts.set(rule, (listCounts.get(rule) ?? 0) + 1);
    }
  }

  for (const folder of ruleFolders) {
    const folderPath = path.join(rulesDir, folder);
    if (!statSync(folderPath).isDirectory()) {
      continue;
    }
    for (const entry of listVisibleEntries(folderPath)) {
      if (!entry.endsWith(".md")) {
        continue;
      }
      const rule = `${folder}/${entry}`;
      const want = INDEX_UNLISTED.has(rule) ? 0 : 1;
      const count = listCounts.get(rule) ?? 0;
      if (count !== want) {
        if (want === 0) {
          fail(
            `${rule}: in ${count} lists; this index file is generated, so it goes in none of skills/meridian/references/rules-*.list`,
          );
        } else {
          fail(
            `${rule}: in ${count} lists; every rule goes in exactly one of skills/meridian/references/rules-*.list`,
          );
        }
      }
      if (EXEMPT.has(rule)) {
        continue;
      }
      const fullPath = path.join(folderPath, entry);
      const formatError = checkRuleFormat(readFileSync(fullPath, "utf8"), entry);
      if (formatError !== null) {
        fail(`skills/meridian/references/rules/${rule}: ${formatError}`);
      }
    }
  }

  const skillsDir = path.join(repoDir, "skills");

  const finish = (outPath: string, body: string): string => {
    const relUnderSkills = toPosixRel(skillsDir, outPath);
    const finalContent = `${body}<!-- end of ${relUnderSkills} -->\n`;
    writeIfChanged(outPath, finalContent, written);
    expectedGenerated.add(outPath);
    return finalContent;
  };

  const buildRulesFile = (routine: string, name: string): void => {
    const outPath = path.join(skillsDir, routine, "references", `rules-${name}.md`);
    const rules = readList(listsDir, name);
    const chunks: string[] = [
      `${GENERATED_STAMP} from skills/meridian/references/rules-${name}.list. Edit the rules under skills/meridian/references/rules/ or the list, then rebuild; do not edit this file. -->\n`,
    ];
    for (const rule of rules) {
      chunks.push(`<!-- rule: ${rule} -->\n`);
      const fullPath = path.join(rulesDir, rule);
      if (existsSync(fullPath)) {
        chunks.push(readFileSync(fullPath, "utf8"));
      } else {
        chunks.push("MISSING RULE\n");
      }
    }
    const finalContent = finish(outPath, chunks.join(""));
    for (const rule of rules) {
      if (!existsSync(path.join(rulesDir, rule))) {
        fail(
          `skills/meridian/references/rules-${name}.list: names ${rule}, and no rule file has that path`,
        );
      }
    }
    for (const err of checkCitations(
      finalContent,
      `skills/meridian/references/rules-${name}.list`,
      rulesDir,
      ruleFolders,
      slugCache,
    )) {
      fail(err);
    }
  };

  const buildRoleFile = (
    routine: string,
    role: string,
    readsCsv: string,
    partsCsv: string,
  ): void => {
    const outPath = path.join(skillsDir, routine, "references", `${role}.md`);
    const parts = partsCsv.split(",").filter((p) => p.length > 0);
    for (const part of parts) {
      const partPath = path.join(skillsDir, routine, "roles", `${part}.md`);
      if (!existsSync(partPath)) {
        fail(
          `skills/${routine}/roles/roles.list: ${role} names the part ${part}, and skills/${routine}/roles/${part}.md is missing`,
        );
        return;
      }
    }
    const reads = readsCsv.split(",").filter((r) => r.length > 0);
    for (const read of reads) {
      if (!existsSync(path.join(listsDir, `rules-${read}.list`))) {
        fail(
          `skills/${routine}/roles/roles.list: ${role} reads ${read}, and skills/meridian/references/rules-${read}.list is missing`,
        );
        return;
      }
    }
    const chunks: string[] = [
      `${GENERATED_STAMP} from skills/${routine}/roles/ (${partsCsv}). Edit the parts there, then rebuild; do not edit this file. -->\n`,
      rulesBlock(readsCsv),
    ];
    for (const part of parts) {
      chunks.push(readFileSync(path.join(skillsDir, routine, "roles", `${part}.md`), "utf8"));
      chunks.push("\n");
    }
    finish(outPath, chunks.join(""));
  };

  const buildKindFile = (routine: string, kind: string, partsCsv: string): void => {
    const outPath = path.join(skillsDir, routine, "kinds", `${kind}.md`);
    const parts = partsCsv.split(",").filter((p) => p.length > 0);
    for (const part of parts) {
      const partPath = path.join(skillsDir, routine, "kinds", kind, `${part}.md`);
      if (!existsSync(partPath)) {
        fail(
          `skills/${routine}/kinds/kinds.list: ${kind} names the part ${part}, and skills/${routine}/kinds/${kind}/${part}.md is missing`,
        );
        return;
      }
    }
    const chunks: string[] = [
      `${GENERATED_STAMP} from skills/${routine}/kinds/${kind}/ (${partsCsv}). Edit the parts there, then rebuild; do not edit this file. -->\n`,
    ];
    for (const part of parts) {
      chunks.push(readFileSync(path.join(skillsDir, routine, "kinds", kind, `${part}.md`), "utf8"));
      chunks.push("\n");
    }
    finish(outPath, chunks.join(""));
  };

  const checkBudget = (outPath: string): void => {
    const rel = toPosixRel(repoDir, outPath);
    const bytes = statSync(outPath).size;
    if (bytes > WARN_BYTE_BUDGET) {
      warnings.push(
        `warning: ${rel}: ${bytes} bytes, over ${WARN_BYTE_BUDGET}; some harnesses truncate single reads (they should read the rest in a second call, but this is not guaranteed)`,
      );
    }
  };

  const routines = listVisibleEntries(skillsDir).filter((entry) =>
    statSync(path.join(skillsDir, entry)).isDirectory(),
  );

  // Build roles and rule files for every routine with roles/roles.list.
  for (const routine of routines) {
    const rolesListPath = path.join(skillsDir, routine, "roles", "roles.list");
    if (!existsSync(rolesListPath)) {
      continue;
    }
    mkdirSync(path.join(skillsDir, routine, "references"), { recursive: true });

    const rawLines = readFileSync(rolesListPath, "utf8").split("\n");
    const parsedEntries: string[][] = [];
    const roleReadLists = new Set<string>();
    const usedRoleParts = new Set<string>();

    for (const rawLine of rawLines) {
      const trimmed = rawLine.trim();
      if (trimmed.length === 0 || trimmed.startsWith("#")) {
        continue;
      }
      const fields = trimmed.split(/\s+/);
      parsedEntries.push(fields);
      if (fields[0] === "role") {
        for (const r of (fields[2] ?? "").split(",")) {
          if (r.length > 0) {
            roleReadLists.add(r);
          }
        }
        for (const p of (fields[3] ?? "").split(",")) {
          if (p.length > 0) {
            usedRoleParts.add(p);
          }
        }
      }
    }

    for (const name of listNames) {
      if (roleReadLists.has(name)) {
        buildRulesFile(routine, name);
      }
    }

    for (const fields of parsedEntries) {
      const kind = fields[0] ?? "";
      const name = fields[1] ?? "";
      const third = fields[2] ?? "";
      const fourth = fields[3] ?? "";
      if (kind === "role") {
        buildRoleFile(routine, name, third, fourth);
      } else if (kind === "rule") {
        const paths = third.split(",").filter((p) => p.length > 0);
        let found = true;
        if (paths.length === 0) {
          fail(`skills/${routine}/roles/roles.list: ${name} names no rule`);
          found = false;
        }
        for (const p of paths) {
          if (!existsSync(path.join(rulesDir, p))) {
            fail(
              `skills/${routine}/roles/roles.list: ${name} names the rule ${p}, and no rule file has that path`,
            );
            found = false;
          }
        }
        if (found) {
          const many = paths.length > 1;
          const what = many
            ? `the rules ${third}. Edit those rules`
            : `the rule ${third}. Edit that rule`;
          const chunks: string[] = [
            `${GENERATED_STAMP} from ${what}, then rebuild; do not edit this file. -->\n`,
          ];
          for (const p of paths) {
            if (many) {
              chunks.push(`<!-- rule: ${p} -->\n`);
            }
            chunks.push(readFileSync(path.join(rulesDir, p), "utf8"));
          }
          finish(path.join(skillsDir, routine, "references", name), chunks.join(""));
        }
      } else {
        fail(`skills/${routine}/roles/roles.list: unknown line kind '${kind}'`);
      }
    }

    const rolesDir = path.join(skillsDir, routine, "roles");
    for (const partPath of findMarkdownFiles(rolesDir, 1)) {
      const rel = toPosixRel(rolesDir, partPath);
      const base = rel.slice(0, -3);
      if (!base.includes("/")) {
        fail(
          `skills/${routine}/roles/${base}.md: role parts must live in a subfolder under roles/, not directly under roles/`,
        );
        continue;
      }
      if (!usedRoleParts.has(base)) {
        fail(`skills/${routine}/roles/${base}.md: no line in roles.list uses it`);
      }
      if (base.endsWith("/head")) {
        continue;
      }
      const formatError = checkRuleFormat(readFileSync(partPath, "utf8"), path.basename(partPath));
      if (formatError !== null) {
        fail(`skills/${routine}/roles/${base}.md: ${formatError}`);
      }
    }
  }

  // Build kinds for every routine with kinds/kinds.list.
  for (const routine of routines) {
    const kindsListPath = path.join(skillsDir, routine, "kinds", "kinds.list");
    if (!existsSync(kindsListPath)) {
      continue;
    }

    const rawLines = readFileSync(kindsListPath, "utf8").split("\n");
    const usedPartsByKind = new Map<string, Set<string>>();

    for (const rawLine of rawLines) {
      const trimmed = rawLine.trim();
      if (trimmed.length === 0 || trimmed.startsWith("#")) {
        continue;
      }
      const fields = trimmed.split(/\s+/);
      const kind = fields[0] ?? "";
      const name = fields[1] ?? "";
      const third = fields[2] ?? "";
      if (kind === "kind") {
        buildKindFile(routine, name, third);
        let used = usedPartsByKind.get(name);
        if (!used) {
          used = new Set<string>();
          usedPartsByKind.set(name, used);
        }
        for (const p of third.split(",")) {
          if (p.length > 0) {
            used.add(p);
          }
        }
      } else {
        fail(`skills/${routine}/kinds/kinds.list: unknown line kind '${kind}'`);
      }
    }

    const kindsDir = path.join(skillsDir, routine, "kinds");
    for (const partPath of findMarkdownFiles(kindsDir, 2)) {
      const rel = toPosixRel(kindsDir, partPath).slice(0, -3);
      const slashIdx = rel.indexOf("/");
      const kname = rel.slice(0, slashIdx);
      const base = rel.slice(slashIdx + 1);
      if (!usedPartsByKind.get(kname)?.has(base)) {
        fail(`skills/${routine}/kinds/${rel}.md: no line in kinds.list uses it`);
      }
      if (base === "head") {
        continue;
      }
      const formatError = checkRuleFormat(readFileSync(partPath, "utf8"), path.basename(partPath));
      if (formatError !== null) {
        fail(`skills/${routine}/kinds/${rel}.md: ${formatError}`);
      }
    }
  }

  // Meridian's own copies of the rule files.
  for (const name of listNames) {
    buildRulesFile("meridian", name);
  }
  for (const entry of listVisibleEntries(listsDir)) {
    if (!entry.startsWith("rules-") || !entry.endsWith(".md")) {
      continue;
    }
    const outPath = path.join(listsDir, entry);
    if (!expectedGenerated.has(outPath)) {
      fail(`${toPosixRel(repoDir, outPath)}: no rules-<name>.list builds it, so delete it`);
    }
    checkBudget(outPath);
  }

  // Check references/ folders for orphans and budgets.
  for (const routine of routines) {
    if (!existsSync(path.join(skillsDir, routine, "roles", "roles.list"))) {
      continue;
    }
    const refsDir = path.join(skillsDir, routine, "references");
    for (const entry of listVisibleEntries(refsDir)) {
      const outPath = path.join(refsDir, entry);
      if (!expectedGenerated.has(outPath)) {
        fail(
          `${toPosixRel(repoDir, outPath)}: no line in roles.list builds it; references/ is generated only, so delete it or move it to roles/`,
        );
      }
      checkBudget(outPath);
    }
  }

  // Check flat kinds/*.md files for orphans and budgets.
  for (const routine of routines) {
    if (!existsSync(path.join(skillsDir, routine, "kinds", "kinds.list"))) {
      continue;
    }
    const kindsDir = path.join(skillsDir, routine, "kinds");
    for (const entry of listVisibleEntries(kindsDir)) {
      if (!entry.endsWith(".md")) {
        continue;
      }
      const outPath = path.join(kindsDir, entry);
      if (!expectedGenerated.has(outPath)) {
        fail(
          `${toPosixRel(repoDir, outPath)}: no line in kinds.list builds it; kinds/*.md is generated only, so delete it or move it into a kind subfolder`,
        );
      }
      checkBudget(outPath);
    }
  }

  // Check rule citations in docs, skills, role parts, and kind parts.
  const citationFiles: string[] = [];
  for (const topDoc of ["README.md", "INSTALL.md", "CONTRIBUTING.md", "AGENTS.md"]) {
    const fullPath = path.join(repoDir, topDoc);
    if (existsSync(fullPath)) {
      citationFiles.push(fullPath);
    }
  }
  for (const routine of routines) {
    const skillDoc = path.join(skillsDir, routine, "SKILL.md");
    if (existsSync(skillDoc)) {
      citationFiles.push(skillDoc);
    }
  }
  for (const routine of routines) {
    const rolesDir = path.join(skillsDir, routine, "roles");
    for (const sub of listVisibleEntries(rolesDir)) {
      const subPath = path.join(rolesDir, sub);
      if (!statSync(subPath).isDirectory()) {
        continue;
      }
      for (const entry of listVisibleEntries(subPath)) {
        if (entry.endsWith(".md")) {
          citationFiles.push(path.join(subPath, entry));
        }
      }
    }
  }
  for (const routine of routines) {
    const kindsDir = path.join(skillsDir, routine, "kinds");
    for (const sub of listVisibleEntries(kindsDir)) {
      const subPath = path.join(kindsDir, sub);
      if (!statSync(subPath).isDirectory()) {
        continue;
      }
      for (const entry of listVisibleEntries(subPath)) {
        if (entry.endsWith(".md")) {
          citationFiles.push(path.join(subPath, entry));
        }
      }
    }
  }

  for (const filePath of citationFiles) {
    const content = readFileSync(filePath, "utf8");
    for (const err of checkCitations(
      content,
      toPosixRel(repoDir, filePath),
      rulesDir,
      ruleFolders,
      slugCache,
    )) {
      fail(err);
    }
  }

  return {
    exitCode: errors.length > 0 ? 1 : 0,
    errors,
    warnings,
    written,
  };
};
