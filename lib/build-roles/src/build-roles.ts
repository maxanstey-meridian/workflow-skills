export const WARN_BYTE_BUDGET = 40_000;
export const GENERATED_STAMP = "<!-- Generated by lib/build-roles/src/cli.ts";

export type BuildRolesResult = {
  exitCode: number;
  errors: string[];
  warnings: string[];
  written: string[];
};

