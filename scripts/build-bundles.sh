#!/bin/sh
# Builds every role's bundle: for each skills/*/references/bundles/<role>.list, concatenates the rules it names, from
# skills/meridian/references/rules/, into the tracked <role>.md beside it. It refuses (exit 1, the bundles still written)
# a list that leaves out a rule one of its rules cites, a cited <path>#<slug> whose file has no heading with that slug,
# a rule file no list names, and a citation in a routine, the README, or AGENTS.md that names no rule file or heading.
# Run it after editing a rule or a list: sh scripts/build-bundles.sh

set -eu
repo=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
rules=$repo/skills/meridian/references/rules
ls "$rules" | grep -qvx '[a-z-]*' && { echo "$rules: holds a name outside [a-z-]" >&2; exit 1; }
cites="($(ls "$rules" | paste -sd '|' -))/[a-z0-9-]+\.md"
status=0

# Prints the heading slugs of a Markdown file (or stdin), one per line: Plumb's githubHeadingSlugs in
# test/catalog.test.mjs, ported line for line, so a slug this build accepts is one Plumb's catalog test accepts. $w and $s
# are JavaScript's \s, which differs from Perl's.
slugs() {
  perl -CSD -0777 -ne '
    my $w = q{\t\n\x0B\f\r \x{a0}\x{1680}\x{2000}-\x{200a}\x{2028}\x{2029}\x{202f}\x{205f}\x{3000}\x{feff}};
    my $s = qr/[$w]/;
    my %counts;
    while (/^ {0,3}#{1,6}$s+(.+?)$s*#*$s*$/mg) {
      my $heading = $1;
      $heading =~ s/!?(?:\[([^\]]*)\])\([^)]*\)/$1/g;
      $heading =~ s/<[^>]+>//g;
      $heading =~ s/[`*_~]//g;
      $heading = lc $heading;
      (my $base = $heading) =~ s/[^\p{L}\p{N}${w}_-]//g;
      $base =~ s/^$s+|$s+$//g;
      $base =~ s/$s/-/g;
      my $count = $counts{$base}++;
      print $count ? "$base-$count\n" : "$base\n";
    }
  ' "$@"
}

expected='provide--inject-pattern
framework-state-usestate
naming
naming-1'
got=$(printf '%s\n' '## Provide / Inject Pattern' '## Framework state (`useState`)' '## Naming' '## Naming' | slugs)
[ "$got" = "$expected" ] || { printf 'the heading slug function is wrong; it gave:\n%s\n' "$got" >&2; exit 1; }

# Refuses each <path>#<slug> cited in the file $1 whose path has no heading with that slug, reporting it against $2.
# A cited anchor runs to whitespace, a backtick, ), ], a comma, or a semicolon, less one trailing full stop.
check_anchors() {
  anchored=$(grep -oE "$cites#[^][:space:]\`),;]+" "$1" | sed 's/\.$//' | sort -u)
  for ref in $anchored; do
    path=${ref%%#*}
    slug=${ref#*#}
    [ -f "$rules/$path" ] && slugs "$rules/$path" | grep -Fxq -- "$slug" \
      || { echo "$2: cites $ref, and $path has no heading with that slug" >&2; status=1; }
  done
}

all=""
for list in "$repo"/skills/*/references/bundles/*.list; do
  [ -e "$list" ] || continue
  rel=${list#"$repo"/}
  bundle=${list%.list}.md
  listed=""
  {
    echo "<!-- Generated by scripts/build-bundles.sh from $rel. Edit the rules under skills/meridian/references/rules/ or the list, then rebuild; do not edit this file. -->"
    while read -r rule || [ -n "$rule" ]; do
      case $rule in "" | "#"*) continue ;; esac
      echo "<!-- rule: $rule -->"
      cat "$rules/$rule"
      listed="$listed$rule
"
    done < "$list"
  } > "$bundle"
  all="$all$listed"
  listed=$(printf '%s' "$listed" | sort -u)
  cited=$(grep -oE "$cites" "$bundle" | sort -u)
  for path in $cited; do
    printf '%s\n' "$listed" | grep -Fxq -- "$path" || { echo "$rel: cites $path, not in the list" >&2; status=1; }
  done
  check_anchors "$bundle" "$rel"
done

for file in "$rules"/*/*.md; do
  rule=${file#"$rules"/}
  printf '%s' "$all" | grep -Fxq -- "$rule" || { echo "$rule: no list names it" >&2; status=1; }
done

for file in "$repo"/README.md "$repo"/AGENTS.md "$repo"/skills/*/SKILL.md "$repo"/skills/*/references/*.md; do
  rel=${file#"$repo"/}
  for path in $(grep -oE "$cites" "$file" | sort -u); do
    [ -f "$rules/$path" ] || { echo "$rel: cites $path, and no rule file has that path" >&2; status=1; }
  done
  check_anchors "$file" "$rel"
done
exit "$status"
