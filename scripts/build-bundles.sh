#!/bin/sh
# Builds every role's bundle: for each skills/*/references/bundles/<role>.list, concatenates the rules it names, from
# skills/meridian/references/rules/, into the tracked <role>.md beside it, and refuses a list that leaves out a rule one of
# its rules cites (exit 1, the bundle still written). Run it after editing a rule or a list: sh scripts/build-bundles.sh

set -eu
repo=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
rules=$repo/skills/meridian/references/rules
ls "$rules" | grep -qvx '[a-z-]*' && { echo "$rules: holds a name outside [a-z-]" >&2; exit 1; }
cites="($(ls "$rules" | paste -sd '|' -))/[a-z0-9-]+\.md"
status=0

for list in "$repo"/skills/*/references/bundles/*.list; do
  [ -e "$list" ] || continue
  rel=${list#"$repo"/}
  bundle=${list%.list}.md
  listed=""
  {
    echo "<!-- Generated by scripts/build-bundles.sh from $rel. Edit the rules under skills/meridian/references/rules/ or the list, then rebuild; do not edit this file. -->"
    while read -r rule || [ -n "$rule" ]; do
      case $rule in "" | "#"*) continue ;; esac
      echo "<!-- rule: $rule -->"
      cat "$rules/$rule"
      listed="$listed$rule
"
    done < "$list"
  } > "$bundle"
  listed=$(printf '%s' "$listed" | sort -u)
  cited=$(grep -oE "$cites" "$bundle" | sort -u)
  for path in $cited; do
    printf '%s\n' "$listed" | grep -Fxq -- "$path" || { echo "$rel: cites $path, not in the list" >&2; status=1; }
  done
done
exit "$status"
